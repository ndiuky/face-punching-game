package engine.text;

public class Glyph {

    public final int width;

    public final int height;

    public final int x;

    public final int y;

    public Glyph(int width, int height, int x, int y) {
        this.width = width;
        this.height = height;
        this.x = x;
        this.y = y;
    }
}